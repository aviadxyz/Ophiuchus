const join = (list: Pt[][]) => list.map((l) => curve(l)).join('')

/** Trunk widths are written at full size and drawn finer, so the plate stays light. */
const THIN = 0.72

/** A finer side branch off the last stretch of each small vessel, alternating sides. */
function forks(list: Pt[][]): Pt[][] {
  return list.flatMap((l, i) => {
    if (l.length < 3) return []
    const a = l[l.length - 2]
    const b = l[l.length - 1]
    const turn = i % 2 ? 0.6 : -0.6
    const dx = (b[0] - a[0]) * 0.75
    const dy = (b[1] - a[1]) * 0.75
    const fx = dx * Math.cos(turn) - dy * Math.sin(turn)
    const fy = dx * Math.sin(turn) + dy * Math.cos(turn)
    return [[a, [a[0] + fx * 0.55, a[1] + fy * 0.5], [a[0] + fx, a[1] + fy]]]
  })
}

function Tree({ core, side, twigs, color }: { core: Vessel[]; side: Vessel[]; twigs: Pt[][]; color: string }) {
  const one = ([w, pts]: Vessel, i: number) => (
    <g key={i}>
      <path className="bf-u" d={curve(pts)} stroke="transparent" strokeWidth={w * THIN + 1.2} />
      <path d={curve(pts)} stroke={color} strokeWidth={w * THIN} />
    </g>
  )
  return (
    <g fill="none">
      {core.map(one)}
      {[undefined, MIRROR].map((t) => (
        <g key={t ?? 'l'} transform={t}>
          {side.map(one)}
          <path d={join(twigs)} stroke={color} strokeWidth="0.7" />
          <path d={join(forks(twigs))} stroke={color} strokeWidth="0.5" />
        </g>
      ))}
    </g>
  )
}

/** Dashes that travel along the main vessels while Blood is chosen. */
function Flow({ core, side, back }: { core: Vessel[]; side: Vessel[]; back?: boolean }) {
  const cls = back ? 'bf-flow bf-flow-back' : 'bf-flow'
  const big = (list: Vessel[]) =>
    list
      .filter(([w]) => w >= 1.5)
      .map(([, pts]) => curve(pts))
      .join('')
  return (
    <g fill="none" stroke={palette.light} strokeOpacity="0.85" strokeWidth="1.1" strokeDasharray="3 15">
      <path className={cls} d={big(core)} />
      <path className={cls} d={big(side)} />
      <path className={cls} d={big(side)} transform={MIRROR} />
    </g>
  )
}

/** Arteries in red and veins in blue. Part of the heart system; Blood lights them too. */
export function Vessels({ view, flow }: { view: LayerView; flow: boolean }) {
  return (
    <Layer view={view}>
      <Tree core={veinsCore} side={veinsSide} twigs={veinTwigs} color={palette.vein} />
      <Tree core={arteriesCore} side={arteriesSide} twigs={arteryTwigs} color={palette.artery} />
      {flow && (
        <>
          <Flow core={veinsCore} side={veinsSide} back />
          <Flow core={arteriesCore} side={arteriesSide} />
        </>
      )}
    </Layer>
  )
}
